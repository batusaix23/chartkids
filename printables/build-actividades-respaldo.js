'use strict';
// printables/build-actividades-respaldo.js — extracts the 58 hand-written activities
// from descargables.html into js/actividades-respaldo.js, the offline library that
// actividad-ia.html shows when the AI is unavailable (daily free budget spent, outage).
// Run: node printables/build-actividades-respaldo.js

const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const html = fs.readFileSync(path.join(ROOT, 'descargables.html'), 'utf8');
const start = html.indexOf('const FICHAS = {'), end = html.indexOf('\nfunction printFicha', start);
if (start < 0 || end < 0) throw new Error('FICHAS block not found in descargables.html');
const FICHAS = new Function(html.slice(start, end).replace('const FICHAS =', 'return') + ';')();

// Page categories (actividad-ia.html chips) ← library categories
const CAT = {
  '🎨 Arte': 'drawing', '✏️ Escritura': 'drawing',
  '✂️ Manualidades': 'crafts',
  '🔬 Experimentos': 'science', '🌿 Naturaleza': 'science',
  '🍳 Cocina': 'cooking',
};

const list = Object.entries(FICHAS).map(([id, f]) => {
  for (const k of ['emoji', 'title_es', 'title_en', 'materials_es', 'steps_es', 'benefits_es', 'tip_es']) {
    if (!f[k] || (Array.isArray(f[k]) && !f[k].length)) throw new Error(`${id}: missing ${k}`);
  }
  const [minAge, maxAge] = String(f.age).split('-').map(Number);
  return {
    id, cat: CAT[f.cat_es] || 'other', minAge: minAge || 3, maxAge: maxAge || minAge || 12,
    emoji: f.emoji, time: f.time,
    es: { title: f.title_es, cat: f.cat_es, materials: f.materials_es, steps: f.steps_es, benefits: f.benefits_es, tip: f.tip_es },
    en: { title: f.title_en, cat: f.cat_en, materials: f.materials_en || f.materials_es, steps: f.steps_en || f.steps_es, benefits: f.benefits_en || f.benefits_es, tip: f.tip_en || f.tip_es },
  };
});

const out = `// js/actividades-respaldo.js — GENERATED by printables/build-actividades-respaldo.js
// from the activity sheets in descargables.html. Do not edit by hand.
// Offline library for actividad-ia.html when the AI is unavailable.
window.ACTIVIDADES_RESPALDO = ${JSON.stringify(list)};
`;
fs.writeFileSync(path.join(ROOT, 'js', 'actividades-respaldo.js'), out);
const byCat = {}; list.forEach(a => { byCat[a.cat] = (byCat[a.cat] || 0) + 1; });
console.log(`✓ js/actividades-respaldo.js: ${list.length} actividades`, byCat);
